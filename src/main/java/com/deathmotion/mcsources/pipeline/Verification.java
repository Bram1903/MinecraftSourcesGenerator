package com.deathmotion.mcsources.pipeline;

import com.deathmotion.mcsources.config.GeneratorConfig;
import com.deathmotion.mcsources.config.RunOptions;
import com.deathmotion.mcsources.decompile.vineflower.VineflowerRun;
import com.deathmotion.mcsources.io.Directories;
import com.deathmotion.mcsources.manifest.MinecraftVersion;
import com.deathmotion.mcsources.manifest.VersionManifest;
import com.deathmotion.mcsources.version.PreparedVersion;
import com.deathmotion.mcsources.version.VersionPreparer;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Collectors;
import java.util.stream.Stream;

public final class Verification {
    private static final int SHOWN_DIFFERENCES = 20;

    private final GeneratorConfig config;
    private final RunOptions options;
    private final VersionManifest manifest;

    public Verification(GeneratorConfig config, RunOptions options, VersionManifest manifest) {
        this.config = config;
        this.options = options;
        this.manifest = manifest;
    }

    public boolean verify(List<MinecraftVersion> versions) throws IOException {
        boolean identical = true;
        VersionPreparer preparer = new VersionPreparer(config, manifest);
        SourceTree tree = new SourceTree(config.sourcesDir());
        for (MinecraftVersion version : versions) {
            long start = System.nanoTime();
            if (!tree.isCurrent(version.id())) {
                Console.line("verify", "%s is not generated by this revision, generate it first", version.id());
                identical = false;
                continue;
            }
            Path generated = tree.directory(version.id());
            PreparedVersion prepared = preparer.prepare(version);
            Map<String, Map<String, String>> canonical = VineflowerRun.decompile(prepared, group -> true,
                    options.decompilerThreads(), config.logsDir().resolve(version.id() + "-verify.log"));
            Path reference = config.workDir().resolve("verify").resolve(version.id());
            Directories.deleteRecursively(reference);
            Set<String> differences = compare(generated, canonical, reference);
            identical &= differences.isEmpty();
            Console.line("verify", "%s: %s in %s", version.id(),
                    differences.isEmpty() ? "identical to a full decompile" : differences.size() + " file(s) differ",
                    Console.since(start));
            differences.stream().limit(SHOWN_DIFFERENCES).forEach(path -> Console.line("verify", "  %s", path));
            if (!differences.isEmpty()) {
                Console.line("verify", "  the full decompile of each differing file is in %s", reference);
            }
        }
        return identical;
    }

    private static Set<String> compare(Path generated, Map<String, Map<String, String>> canonical, Path reference)
            throws IOException {
        Set<String> differences = new TreeSet<>();
        Set<String> expected = new TreeSet<>();
        for (Map.Entry<String, Map<String, String>> group : canonical.entrySet()) {
            for (Map.Entry<String, String> file : group.getValue().entrySet()) {
                String relative = SourceTree.relativePath(group.getKey(), file.getKey());
                expected.add(relative);
                Path actual = generated.resolve(relative);
                byte[] expectedBytes = file.getValue().getBytes(StandardCharsets.UTF_8);
                boolean present = Files.exists(actual);
                if (!present || !Arrays.equals(Files.readAllBytes(actual), expectedBytes)) {
                    differences.add((present ? "differs " : "missing ") + relative);
                    Path copy = reference.resolve(relative);
                    Files.createDirectories(copy.getParent());
                    Files.write(copy, expectedBytes);
                }
            }
        }
        try (Stream<Path> walk = Files.walk(generated)) {
            walk.filter(path -> path.toString().endsWith(".java"))
                    .map(path -> generated.relativize(path).toString().replace('\\', '/'))
                    .filter(relative -> !expected.contains(relative))
                    .collect(Collectors.toCollection(TreeSet::new))
                    .forEach(relative -> differences.add("extra " + relative));
        }
        return differences;
    }
}
